export const SOAP_SUB_CATEGORIES = ['soaps', 'brightening', 'acne', 'moisture', 'detox', 'soothing'];

export function matchesProductCategory(
  product: { category: string; featuredInPrompt?: boolean },
  selectedCategory: string
): boolean {
  if (!selectedCategory || selectedCategory === 'all') return true;
  if (selectedCategory === 'prompt_featured') return Boolean(product.featuredInPrompt);

  // Direct exact category match always returns true
  if (product.category === selectedCategory) return true;

  // Department-level grouping for default sub-categories
  if (selectedCategory === 'soaps') {
    return SOAP_SUB_CATEGORIES.includes(product.category);
  }
  if (selectedCategory === 'hair') {
    return ['hair', 'shampoos', 'oils'].includes(product.category);
  }
  if (selectedCategory === 'skincare') {
    return ['skincare', 'spray'].includes(product.category);
  }

  return false;
}

